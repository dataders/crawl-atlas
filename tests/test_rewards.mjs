import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const data=JSON.parse(readFileSync('site/dist/data/series.json','utf8'));
const code=readFileSync('site/dist/rewards.js','utf8');
const ctx=vm.createContext({});
vm.runInContext(code.slice(0,code.indexOf('function renderRewards')),ctx);
const boundary=data.events.find(e=>e.id==='reward-imani-tier').progress;
ctx.early=data.events.filter(e=>e.progress<boundary);
ctx.late=data.events;
assert.equal(vm.runInContext('rewardRows(early.filter(e=>e.id==="reward-imani-award"),early)[0].tier',ctx),'');
assert.equal(vm.runInContext('rewardRows(late.filter(e=>e.id==="reward-imani-award"),late)[0].tier',ctx),'Silver');
assert.equal(vm.runInContext('rewardRows([],[]).length',ctx),0);
const fields=new Map();
ctx.document={querySelector(key){if(!fields.has(key))fields.set(key,{value:'',innerHTML:'',textContent:''});return fields.get(key);}};
ctx.esc=String;ctx.visibleEvents=()=>data.events;
vm.runInContext(code.slice(code.indexOf('function renderRewards'),code.indexOf("for (const id of ['search'")),ctx);
vm.runInContext('renderRewards(late.filter(e=>e.subject==="Imani C."))',ctx);
assert.ok(fields.get('#reward-results').innerHTML.includes('Silver'));
fields.get('#reward-search').value='Hammer';
vm.runInContext('renderRewards(late.filter(e=>e.subject==="Imani C."))',ctx);
assert.ok(fields.get('#reward-results').innerHTML.includes('Enchanted Hammer'));
assert.ok(!fields.get('#reward-results').innerHTML.includes('Celestial'));
console.log('Rewards: later tier revelation, empty cast, character and search filters passed.');
