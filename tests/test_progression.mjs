import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const data=JSON.parse(readFileSync('site/dist/data/series.json','utf8'));
const imani=data.characters.find(c=>c.name==='Imani C.');
const events=data.events.filter(e=>e.subject===imani.name);
const growth=events.find(e=>e.action==='increase');
const fields=new Map();
const $=key=>{if(!fields.has(key))fields.set(key,{innerHTML:'',textContent:'',setAttribute(){},querySelectorAll(){return [];}});return fields.get(key);};
const state={data,progress:1,chartMetric:'level'};
const context=vm.createContext({state,$,esc:String,SERIES:{},EVENT_COLORS:{skill:'red',item:'green',party:'blue'},events,imani});
const source=readFileSync('site/dist/app.js','utf8');
vm.runInContext(source.slice(source.indexOf('function characterState('),source.indexOf('function inventoryAt(')),context);
vm.runInContext(source.slice(source.indexOf('function renderChart('),source.indexOf('function renderCharacters(')),context);
context.before=events.filter(e=>e.progress<growth.progress);
assert.equal(vm.runInContext('characterState(imani,before).level',context),24);
assert.equal(vm.runInContext('characterState(imani,events).level',context),null);
vm.runInContext('renderChart(events,[])',context);
assert.ok($('#level-uncertainty').innerHTML.includes('not a maximum or a current level'));
assert.ok($('#progress-chart').innerHTML.includes('↑ Level increased · total unknown'));
assert.ok($('#milestone-strip').innerHTML.includes('Increased · total unknown'));
const path=$('#progress-chart').innerHTML.match(/class="level-path"[^>]* d="([^"]+)"/)[1];
assert.ok(!path.includes(' H '),'Old level must not continue horizontally to reading boundary');
const last=events.filter(e=>e.type==='level' && Number.isFinite(e.level)).at(-1);
const expectedX=64+last.progress*(1100-64-28);
assert.ok(path.includes(` L ${expectedX} `),'Guide ends at last exact numeric observation');
assert.ok($('#chart-explanation').textContent.includes('after the last dot is unknown'));
console.log('Progression: unknown later total, visible unquantified increase, no carried-forward plateau passed.');
